def seed_designs():
    db = SessionLocal()
    try:
        print("[DB] Seeding/Updating 24 Royal Car Flower Decoration Designs...")
        for d in DESIGNS:
            existing = db.query(DecorationPackage).filter(DecorationPackage.id == d["id"]).first()
            if existing:
                existing.name = d["name"]
                existing.slug = d["slug"]
                existing.theme = d["theme"]
                existing.category = d["category"]
                existing.badge = d["badge"]
                existing.subtitle = d["subtitle"]
                existing.starting_price = d["starting_price"]
                existing.description = d["description"]
                existing.image = d["image"]
                existing.included_items = d["included_items"]
                existing.compatible_categories = d["compatible_categories"]
                existing.duration = d["duration"]
                existing.service_areas = d["service_areas"]
                existing.is_active = True
                existing.sort_order = d["sort_order"]
                print(f"Updated ID {d['id']}: {d['name']}")
            else:
                pkg = DecorationPackage(
                    id=d["id"],
                    name=d["name"],
                    slug=d["slug"],
                    theme=d["theme"],
                    category=d["category"],
                    badge=d["badge"],
                    subtitle=d["subtitle"],
                    starting_price=d["starting_price"],
                    description=d["description"],
                    image=d["image"],
                    gallery=[],
                    included_items=d["included_items"],
                    compatible_categories=d["compatible_categories"],
                    duration=d["duration"],
                    service_areas=d["service_areas"],
                    is_active=True,
                    sort_order=d["sort_order"],
                )
                db.add(pkg)
                print(f"Added ID {d['id']}: {d['name']}")
        db.commit()
        print("✓ Successfully synchronized all 24 car flower decoration designs in MySQL!")
    except Exception as e:
        db.rollback()
        print("Error during seed:", e)
    finally:
        db.close()

